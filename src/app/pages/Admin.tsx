// CreateUserModal — admin-only inline form that invokes the
// admin-create-user edge function (service_role) then sends
// the auto-generated-account email with the temp password.
// ============================================================
interface CreateUserModalProps {
  onClose: () => void;
  onCreated: (newUser: AdminUser) => void;
}

function CreateUserModal({ onClose, onCreated }: CreateUserModalProps) {
  const [firstName, setFirstName] = useState("");
  const [lastName, setLastName] = useState("");
  const [email, setEmail] = useState("");
  const [password, setPassword] = useState("");
  const [role, setRole] = useState<
    "Buyer" | "Photographer" | "Contributor" | "Enterprise" | "Admin"
  >("Buyer");
  const [status, setStatus] = useState<"Active" | "Pending" | "Suspended" | "Blocked">("Active");
  const [verificationStatus, setVerificationStatus] = useState<
    "unverified" | "pending" | "verified" | "rejected"
  >("unverified");
  const [phone, setPhone] = useState("");
  const [occupation, setOccupation] = useState("");
  const [location, setLocation] = useState("");
  const [isCreating, setIsCreating] = useState(false);

  const handleSubmit = async (e: React.FormEvent) => {
    e.preventDefault();
    const cleanEmail = email.trim().toLowerCase();
    const cleanFirst = firstName.trim();
    const cleanLast = lastName.trim();
    if (!cleanEmail || !cleanFirst) {
      toast.error("First name and email are required");
      return;
    }
    if (password && password.length < 10) {
      toast.error("Password must be at least 10 characters");
      return;
    }
    const fullName = `${cleanFirst} ${cleanLast}`.trim();
    setIsCreating(true);
    try {
      const res: AdminCreateUserResult = await adminCreateUser({
        email: cleanEmail,
        password: password || undefined,
        name: fullName,
        role,
        status,
        verificationStatus,
        phone: phone || undefined,
        occupation: occupation || undefined,
        location: location || undefined,
      });

      // Send the welcome email with temp password (only when we auto-generated it)
      if (res.tempPasswordGenerated && res.password) {
        await sendAutoGeneratedAccountEmail(cleanEmail, fullName, res.password).catch((err) =>
          console.error("welcome email failed", err),
        );
      }

      // Push the new user into the list
      onCreated({
        id: res.user.id,
        name: res.user.name,
        email: res.user.email,
        role: res.user.role as AdminUser["role"],
        status: res.user.status as AdminUser["status"],
        verificationStatus: res.user.verificationStatus,
        joined: new Date().toISOString(),
        phone: phone || undefined,
        occupation: occupation || undefined,
        location: location || undefined,
      });

      toast.success(
        res.tempPasswordGenerated
          ? `Account created. Temp password sent to ${cleanEmail}`
          : "Account created successfully",
      );
      onClose();
    } catch (err: any) {
      toast.error(err?.message || "Failed to create user");
    } finally {
      setIsCreating(false);
    }
  };

  return (
    <div
      className="fixed inset-0 z-[70] flex items-center justify-center bg-[#16231f]/55 backdrop-blur-sm p-4"
      onClick={onClose}
    >
      <div
        className="bg-white rounded-3xl shadow-2xl border border-[#ececec] w-full max-w-lg max-h-[95vh] overflow-y-auto"
        onClick={(e) => e.stopPropagation()}
      >
        <div className="sticky top-0 bg-white p-6 border-b border-[#ececec] flex items-center justify-between rounded-t-3xl z-10">
          <div className="flex items-center gap-3">
            <div className="bg-[#1e4a3f]/10 text-[#1e4a3f] rounded-full p-2">
              <UserPlus className="size-5" />
            </div>
            <div>
              <h2 className="font-serif text-xl text-[#18211f]">Create User</h2>
              <p className="text-xs text-[#758078]">Provision a new account with admin overrides</p>
            </div>
          </div>
          <button
            onClick={onClose}
            className="p-2 rounded-full hover:bg-[#f0f4f2] text-[#6b716d] transition"
            aria-label="Close"
          >
            <X className="size-5" />
          </button>
        </div>

        <form onSubmit={handleSubmit} className="p-6 space-y-4">
          <div className="grid grid-cols-1 sm:grid-cols-2 gap-4">
            <Field
              label="First Name"
              value={firstName}
              onChange={(e) => setFirstName(e.target.value)}
              placeholder="John"
            />
            <Field
              label="Last Name"
              value={lastName}
              onChange={(e) => setLastName(e.target.value)}
              placeholder="Doe"
            />
          </div>

          <Field
            label="Email"
            type="email"
            value={email}
            onChange={(e) => setEmail(e.target.value)}
            placeholder="john.doe@example.com"
          />

          <div>
            <label className="text-[10px] font-mono tracking-wider text-[#758078] uppercase mb-1.5 block">
              Password
            </label>
            <input
              type="text"
              value={password}
              onChange={(e) => setPassword(e.target.value)}
              placeholder="Leave blank to auto-generate temp password"
              className="w-full border border-[#ececec] rounded-xl bg-white px-4 py-2.5 text-sm outline-none focus:border-[#1e4a3f] focus:ring-2 focus:ring-[#1e4a3f]/10"
            />
            <p className="text-[11px] text-[#758078] mt-1">
              Minimum 10 characters. Blank = random temp password emailed to user.
            </p>
          </div>

          <div className="grid grid-cols-1 sm:grid-cols-3 gap-3">
            <div>
              <label className="text-[10px] font-mono tracking-wider text-[#758078] uppercase mb-1.5 block">
                Role
              </label>
              <select
                value={role}
                onChange={(e) => {
                  const next = e.target.value as typeof role;
                  setRole(next);
                  // Creating a contributor is itself the vetting decision, so
                  // open their portal rather than sending them to pay the
                  // verification fee to get in.
                  setVerificationStatus(
                    next === "Photographer" || next === "Contributor" ? "verified" : "unverified",
                  );
                }}
                className="w-full border border-[#ececec] rounded-xl bg-white px-3 py-2.5 text-sm outline-none focus:border-[#1e4a3f] focus:ring-2 focus:ring-[#1e4a3f]/10"
              >
                <option value="Buyer">Buyer</option>
                <option value="Photographer">Photographer</option>
                <option value="Contributor">Contributor</option>
                <option value="Enterprise">Enterprise</option>
                <option value="Admin">Admin</option>
              </select>
            </div>
            <div>
              <label className="text-[10px] font-mono tracking-wider text-[#758078] uppercase mb-1.5 block">
                Status
              </label>
              <select
                value={status}
                onChange={(e) => setStatus(e.target.value as typeof status)}
                className="w-full border border-[#ececec] rounded-xl bg-white px-3 py-2.5 text-sm outline-none focus:border-[#1e4a3f] focus:ring-2 focus:ring-[#1e4a3f]/10"
              >
                <option value="Active">Active</option>
                <option value="Pending">Pending</option>
                <option value="Suspended">Suspended</option>
                <option value="Blocked">Blocked</option>
              </select>
            </div>
            <div>
              <label className="text-[10px] font-mono tracking-wider text-[#758078] uppercase mb-1.5 block">
                Verification
              </label>
              <select
                value={verificationStatus}
                onChange={(e) => setVerificationStatus(e.target.value as typeof verificationStatus)}
                className="w-full border border-[#ececec] rounded-xl bg-white px-3 py-2.5 text-sm outline-none focus:border-[#1e4a3f] focus:ring-2 focus:ring-[#1e4a3f]/10"
              >
                <option value="unverified">Unverified</option>
                <option value="pending">Pending</option>
                <option value="verified">Verified</option>
                <option value="rejected">Rejected</option>
              </select>
            </div>
          </div>

          <div className="grid grid-cols-1 sm:grid-cols-2 gap-4">
            <Field
              label="Phone (optional)"
              value={phone}
              onChange={(e) => setPhone(e.target.value)}
              placeholder="+1 234 567 8900"
            />
            <Field
              label="Occupation (optional)"
              value={occupation}
              onChange={(e) => setOccupation(e.target.value)}
              placeholder="Freelance Photographer"
            />
          </div>

          <Field
            label="Location (optional)"
            value={location}
            onChange={(e) => setLocation(e.target.value)}
            placeholder="London, UK"
          />

          <div className="pt-3 border-t border-[#ececec] flex flex-col sm:flex-row gap-3">
            <button
              type="button"
              onClick={onClose}
              className="flex-1 bg-white border border-[#ececec] text-[#18211f] text-sm font-semibold py-3 rounded-full hover:bg-[#f8f9f7] transition"
            >
              Cancel
            </button>
            <button
              type="submit"
              disabled={isCreating}
              className="flex-1 bg-[#1e4a3f] py-3 text-sm font-semibold text-white rounded-full hover:bg-[#123b31] transition disabled:opacity-50 disabled:cursor-not-allowed flex items-center justify-center gap-2"
            >
              {isCreating ? "Creating..." : "Create User"}
            </button>
          </div>
        </form>
      </div>
    </div>
  );
}
